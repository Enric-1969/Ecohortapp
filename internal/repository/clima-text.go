// GetClimaText retorna els quatre elements de text de la interfície de Fyne
func GetClimaText(app *domain.Config) (*canvas.Text, *canvas.Text, *canvas.Text, *canvas.Text, error) {
	codiMunicipi := app.Municipi
	if codiMunicipi == "" && app.UserConfig.MunicipioCodigo != "" {
		codiMunicipi = app.UserConfig.MunicipioCodigo
	}
	if codiMunicipi == "" {
		codiMunicipi = "08001"
	}

	urlDades, err := GetPreUrl(codiMunicipi)
	if err != nil {
		return nil, nil, nil, nil, err
	}

	prediccio, err := GetPrediccio(urlDades)
	if err != nil {
		return nil, nil, nil, nil, err
	}

	colorPrecipitacio := color.NRGBA{R: 0, G: 180, B: 0, A: 255}
	if prediccio.ProbPrecipitacio < 50 {
		colorPrecipitacio = color.NRGBA{R: 180, G: 0, B: 0, A: 255}
	}

	textColor := theme.ForegroundColor()

	precipitacioTxt := fmt.Sprintf("Precipitació: %d%%", prediccio.ProbPrecipitacio)
	tempMaxTxt := fmt.Sprintf("Temp. Max: %d°C", prediccio.TemperaturaMax)
	tempMinTxt := fmt.Sprintf("Temp. Min: %d°C", prediccio.TemperaturaMin)
	humitatTxt := fmt.Sprintf("Humitat: %d%%", prediccio.HumitatRelativa)

	precipitacio := canvas.NewText(precipitacioTxt, colorPrecipitacio)
	tempMax := canvas.NewText(tempMaxTxt, textColor)
	tempMin := canvas.NewText(tempMinTxt, textColor)
	humitat := canvas.NewText(humitatTxt, textColor)

	precipitacio.Alignment = fyne.TextAlignLeading
	tempMax.Alignment = fyne.TextAlignCenter
	tempMin.Alignment = fyne.TextAlignCenter
	humitat.Alignment = fyne.TextAlignTrailing

	return precipitacio, tempMax, tempMin, humitat, nil
}

func GetPreUrl(codiMunicipi string) (string, error) {
	apiKeyEnv := os.Getenv("AEMET_API_KEY")
	url := fmt.Sprintf("https://aemet.es", codiMunicipi, apiKeyEnv)

	req, err := http.NewRequest("GET", url, nil)
	if err != nil {
		return "", fmt.Errorf("error creant la petició HTTP: %w", err)
	}

	req.Header.Add("cache-control", "no-cache")
	req.Header.Set("User-Agent", "EcoHortApp/1.0 (ecohortapp@cibernarium.cat)")

	res, err := http.DefaultClient.Do(req)
	if err != nil {
		return "", err
	}
	defer res.Body.Close()

	body, err := io.ReadAll(res.Body)
	if err != nil {
		return "", err
	}

	var preUrl domain.PreUrl
	err = json.Unmarshal(body, &preUrl)
	if err != nil {
		return "", err
	}

	if preUrl.Url == "" {
		return "", fmt.Errorf("AEMET no ha retornat URL")
	}

	return preUrl.Url, nil
}

func GetPrediccio(url string) (*domain.Diaria, error) {
	req, err := http.NewRequest("GET", url, nil)
	if err != nil {
		return nil, fmt.Errorf("error creant la petició HTTP: %w", err)
	}

	req.Header.Add("cache-control", "no-cache")
	req.Header.Set("User-Agent", "EcoHortApp/1.0 (ecohortapp@cibernarium.cat)")

	res, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()

	body, err := io.ReadAll(res.Body)
	if err != nil {
		return nil, err
	}

	var prediccio domain.AutoGenerated
	err = json.Unmarshal(body, &prediccio)
	if err != nil {
		return nil, err
	}

	// Tu struct AutoGenerated es un array, accedemos al primer elemento de forma segura
	if len(prediccio) == 0 || len(prediccio[0].Prediccion.Dia) == 0 {
		return nil, errors.New("la resposta d'AEMET no conté dades de predicció vàlides")
	}

	diaActual := prediccio[0].Prediccion.Dia[0]

	var precipitacio int
	// ProbPrecipitacion también es un array en tu domain.go, extraemos la primera posición
	if len(diaActual.ProbPrecipitacion) > 0 {
		precipitacio = diaActual.ProbPrecipitacion[0].Value
	}

	tempMax := diaActual.Temperatura.Maxima
	tempMin := diaActual.Temperatura.Minima
	humitat := diaActual.HumedadRelativa.Maxima

	currentInfo := domain.Diaria{
		ProbPrecipitacio: precipitacio,
		TemperaturaMax:   tempMax,
		TemperaturaMin:   tempMin,
		HumitatRelativa:  humitat,
		Time:             time.Now(),
	}

	return &currentInfo, nil
}
